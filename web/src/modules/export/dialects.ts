import type { ColumnSpec, ForeignKeySpec, TableSpec } from "./types";

export type SupportedEngine = "postgres" | "mysql" | "sqlite";

/**
 * Quote định danh (tên bảng, tên cột, tên ràng buộc) theo từng dialect:
 * - Postgres: dùng dấu ngoặc kép "" và escape dấu ngoặc kép bên trong bằng cách nhân đôi ("")
 * - MySQL: dùng dấu backtick `` và escape dấu backtick bên trong bằng cách nhân đôi (``)
 * - SQLite: dùng dấu backtick `` và escape dấu backtick bên trong bằng cách nhân đôi (``)
 */
export function quoteIdentifier(name: string, engine: SupportedEngine): string {
  if (engine === "postgres") {
    return `"${name.replace(/"/g, '""')}"`;
  }
  return `\`${name.replace(/`/g, "``")}\``;
}

/**
 * Escape chuỗi văn bản cho literal trong SQL (nháy đơn '')
 */
export function escapeSingleQuote(str: string): string {
  return str.replace(/'/g, "''");
}

/**
 * Hiển thị tên engine chuẩn cho header metadata
 */
export function formatEngineDisplayName(engine: SupportedEngine): string {
  switch (engine) {
    case "postgres":
      return "PostgreSQL";
    case "mysql":
      return "MySQL";
    case "sqlite":
      return "SQLite";
  }
}

/**
 * Kiểm tra engine có hỗ trợ tách câu lệnh ALTER TABLE ... ADD CONSTRAINT FOREIGN KEY không.
 * Postgres và MySQL hỗ trợ đầy đủ. SQLite không hỗ trợ cú pháp này (phải inline lúc CREATE TABLE).
 */
export function supportsAlterForeignKey(engine: SupportedEngine): boolean {
  return engine === "postgres" || engine === "mysql";
}

/**
 * Sinh định nghĩa cột theo dialect
 */
export function formatColumnDefinition(
  col: ColumnSpec,
  engine: SupportedEngine,
  isSinglePk: boolean,
): string {
  const parts: string[] = [];
  parts.push(quoteIdentifier(col.name, engine));
  parts.push(col.type);

  // SQLite identity xử lý đặc biệt khi là single primary key
  const isSqliteIdentitySinglePk =
    engine === "sqlite" && Boolean(col.isIdentity) && isSinglePk && Boolean(col.primaryKey);

  if (isSqliteIdentitySinglePk) {
    parts.push("PRIMARY KEY AUTOINCREMENT");
  } else if (
    engine === "postgres" &&
    col.isIdentity &&
    !col.type.toLowerCase().includes("serial")
  ) {
    parts.push("GENERATED BY DEFAULT AS IDENTITY");
  }

  // Cột khóa chính hoặc nullable === false -> NOT NULL
  // Trừ trường hợp SQLite PRIMARY KEY AUTOINCREMENT đã tự quản lý
  if (col.nullable === false || (col.primaryKey && !isSqliteIdentitySinglePk)) {
    parts.push("NOT NULL");
  }

  // MySQL identity
  if (engine === "mysql" && col.isIdentity) {
    parts.push("AUTO_INCREMENT");
  }

  // Default value
  if (col.defaultValue !== undefined && col.defaultValue !== null && col.defaultValue.trim() !== "") {
    parts.push(`DEFAULT ${col.defaultValue.trim()}`);
  }

  // Unique (nếu không phải primary key)
  if (col.unique && !col.primaryKey && !isSqliteIdentitySinglePk) {
    parts.push("UNIQUE");
  }

  // MySQL inline column comment
  if (engine === "mysql" && col.comment) {
    parts.push(`COMMENT '${escapeSingleQuote(col.comment)}'`);
  }

  return parts.join(" ");
}

/**
 * Sinh table constraint cho Primary Key
 */
export function formatPrimaryKeyConstraint(
  pkColumns: string[],
  engine: SupportedEngine,
): string {
  const quotedCols = pkColumns.map((col) => quoteIdentifier(col, engine)).join(", ");
  return `PRIMARY KEY (${quotedCols})`;
}

/**
 * Sinh inline Foreign Key constraint cho CREATE TABLE
 */
export function formatInlineForeignKeyConstraint(
  fk: ForeignKeySpec,
  tableName: string,
  engine: SupportedEngine,
): string {
  const fkName = fk.name?.trim() || `fk_${tableName}_${fk.columns.join("_")}`;
  const quotedFkName = quoteIdentifier(fkName, engine);
  const quotedCols = fk.columns.map((c) => quoteIdentifier(c, engine)).join(", ");
  const quotedRefTable = quoteIdentifier(fk.refTable, engine);
  const refCols = fk.refColumns && fk.refColumns.length > 0 ? fk.refColumns : fk.columns;
  const quotedRefCols = refCols.map((c) => quoteIdentifier(c, engine)).join(", ");

  let sql = `CONSTRAINT ${quotedFkName} FOREIGN KEY (${quotedCols}) REFERENCES ${quotedRefTable} (${quotedRefCols})`;
  if (fk.onDelete) {
    sql += ` ON DELETE ${fk.onDelete.toUpperCase()}`;
  }
  if (fk.onUpdate) {
    sql += ` ON UPDATE ${fk.onUpdate.toUpperCase()}`;
  }
  return sql;
}

/**
 * Sinh câu lệnh ALTER TABLE ... ADD CONSTRAINT FOREIGN KEY cho cycle resolution ở cuối file
 */
export function formatAlterTableForeignKey(
  fk: ForeignKeySpec,
  tableName: string,
  engine: SupportedEngine,
): string {
  const quotedTable = quoteIdentifier(tableName, engine);
  const fkName = fk.name?.trim() || `fk_${tableName}_${fk.columns.join("_")}`;
  const quotedFkName = quoteIdentifier(fkName, engine);
  const quotedCols = fk.columns.map((c) => quoteIdentifier(c, engine)).join(", ");
  const quotedRefTable = quoteIdentifier(fk.refTable, engine);
  const refCols = fk.refColumns && fk.refColumns.length > 0 ? fk.refColumns : fk.columns;
  const quotedRefCols = refCols.map((c) => quoteIdentifier(c, engine)).join(", ");

  let sql = `ALTER TABLE ${quotedTable} ADD CONSTRAINT ${quotedFkName} FOREIGN KEY (${quotedCols}) REFERENCES ${quotedRefTable} (${quotedRefCols})`;
  if (fk.onDelete) {
    sql += ` ON DELETE ${fk.onDelete.toUpperCase()}`;
  }
  if (fk.onUpdate) {
    sql += ` ON UPDATE ${fk.onUpdate.toUpperCase()}`;
  }
  sql += ";";
  return sql;
}

/**
 * Sinh comment câu lệnh cho Postgres (COMMENT ON TABLE / COMMENT ON COLUMN)
 */
export function formatPostgresComments(table: TableSpec): string[] {
  const statements: string[] = [];
  const quotedTable = quoteIdentifier(table.name, "postgres");

  if (table.comment) {
    statements.push(`COMMENT ON TABLE ${quotedTable} IS '${escapeSingleQuote(table.comment)}';`);
  }

  for (const col of table.columns) {
    if (col.comment) {
      const quotedCol = quoteIdentifier(col.name, "postgres");
      statements.push(
        `COMMENT ON COLUMN ${quotedTable}.${quotedCol} IS '${escapeSingleQuote(col.comment)}';`,
      );
    }
  }

  return statements;
}
