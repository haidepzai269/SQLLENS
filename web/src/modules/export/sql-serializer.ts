import { buildDependencyGraph, topoSort } from "./dependency-graph";
import {
  escapeSingleQuote,
  formatAlterTableForeignKey,
  formatColumnDefinition,
  formatEngineDisplayName,
  formatInlineForeignKeyConstraint,
  formatPostgresComments,
  formatPrimaryKeyConstraint,
  quoteIdentifier,
  supportsAlterForeignKey,
  type SupportedEngine,
} from "./dialects";
import type { ForeignKeySpec, TableSpec } from "./types";

export interface SerializeSchemaInput {
  tables: TableSpec[];
  engine: SupportedEngine;
  projectName: string;
  now: Date;
}

/**
 * Serializer sinh file .sql hoàn chỉnh từ danh sách TableSpec theo dialect và thứ tự tô-pô.
 * - Sắp xếp bảng cha trước bảng con.
 * - Với Postgres và MySQL: Tách các khóa ngoại thuộc chu trình (cycle FKs) ra khối ALTER TABLE ở cuối file.
 * - Với SQLite: Khóa ngoại được inline trong CREATE TABLE (SQLite không hỗ trợ ALTER TABLE ADD CONSTRAINT).
 * - Quote định danh chính xác theo dialect ("", ``).
 * - Kết quả bảo đảm tính tất định 100% cùng đầu vào và cùng now.
 */
export function serializeSchema(input: SerializeSchemaInput): string {
  const { tables, engine, projectName, now } = input;

  // Trường hợp schema rỗng
  if (!tables || tables.length === 0) {
    const emptyHeader = [
      "-- ==============================================================",
      "-- Generated by SQLLens Architecture Platform (https://sqllens.com)",
      `-- Engine: ${formatEngineDisplayName(engine)} (${engine})`,
      `-- Exported: ${now.toISOString()}`,
      `-- Project: ${projectName.trim() || "Untitled Project"}`,
      `-- Dependency Order: []`,
      "-- ==============================================================",
    ].join("\n");
    return emptyHeader + "\n";
  }

  // 1. Phân tích đồ thị phụ thuộc và phát hiện chu trình
  const initialGraph = buildDependencyGraph(tables);
  const initialTopo = topoSort(initialGraph);

  // Thu thập các cạnh phụ thuộc nằm trong bất kỳ chu trình nào
  const cycleEdges = new Set<string>();
  for (const cycle of initialTopo.cycles) {
    for (let i = 0; i < cycle.length - 1; i++) {
      cycleEdges.add(`${cycle[i].toLowerCase()}->${cycle[i + 1].toLowerCase()}`);
    }
  }

  const isCycleSafe = supportsAlterForeignKey(engine);
  const deferredFKs: { tableName: string; fk: ForeignKeySpec }[] = [];

  // 2. Dựng đồ thị không chu trình để tính toán creationOrder đầy đủ cho mọi engine
  const topoTables: TableSpec[] = tables.map((t) => {
    const fks = t.foreignKeys || [];
    if (cycleEdges.size === 0) return t;

    const acyclicFks = fks.filter(
      (fk) => !cycleEdges.has(`${t.name.toLowerCase()}->${fk.refTable.toLowerCase()}`),
    );
    return {
      ...t,
      foreignKeys: acyclicFks,
    };
  });

  const acyclicGraph = buildDependencyGraph(topoTables);
  const acyclicTopo = topoSort(acyclicGraph);
  const creationOrder = acyclicTopo.order;

  // 3. Với Postgres và MySQL: gom các cycle FKs vào deferredFKs
  if (isCycleSafe && cycleEdges.size > 0) {
    for (const t of tables) {
      for (const fk of t.foreignKeys || []) {
        const edgeKey = `${t.name.toLowerCase()}->${fk.refTable.toLowerCase()}`;
        if (cycleEdges.has(edgeKey)) {
          deferredFKs.push({ tableName: t.name, fk });
        }
      }
    }
  }

  // Sắp xếp deferredFKs theo thứ tự tất định (theo thứ tự bảng tạo, rồi theo tên cột nguồn)
  deferredFKs.sort((a, b) => {
    const idxA = creationOrder.indexOf(a.tableName);
    const idxB = creationOrder.indexOf(b.tableName);
    if (idxA !== idxB && idxA !== -1 && idxB !== -1) {
      return idxA - idxB;
    }
    const tableCmp = a.tableName.localeCompare(b.tableName);
    if (tableCmp !== 0) return tableCmp;
    const colA = a.fk.columns.join(",");
    const colB = b.fk.columns.join(",");
    const colCmp = colA.localeCompare(colB);
    if (colCmp !== 0) return colCmp;
    return a.fk.refTable.localeCompare(b.fk.refTable);
  });

  // Bản đồ tra cứu bảng theo tên canonical
  const originalTableMap = new Map<string, TableSpec>();
  for (const t of tables) {
    originalTableMap.set(t.name.toLowerCase(), t);
  }

  // 4. Header comment
  const headerLines = [
    "-- ==============================================================",
    "-- Generated by SQLLens Architecture Platform (https://sqllens.com)",
    `-- Engine: ${formatEngineDisplayName(engine)} (${engine})`,
    `-- Exported: ${now.toISOString()}`,
    `-- Project: ${projectName.trim() || "Untitled Project"}`,
    `-- Dependency Order: [${creationOrder.join(", ")}]`,
    "-- ==============================================================",
  ];

  const sections: string[] = [headerLines.join("\n")];

  // 5. Sinh các câu lệnh CREATE TABLE theo đúng creationOrder
  for (const tableName of creationOrder) {
    const table = originalTableMap.get(tableName.toLowerCase());
    if (!table) continue;

    const pkCols = (table.columns || []).filter((c) => c.primaryKey);
    const isSinglePk = pkCols.length === 1;

    // Định nghĩa các cột
    const colDefs = (table.columns || []).map((col) =>
      formatColumnDefinition(col, engine, isSinglePk),
    );

    // Các ràng buộc bảng (table constraints)
    const constraints: string[] = [];

    // Primary key constraint (nếu không phải trường hợp SQLite single-pk autoincrement đã inline)
    const isSqliteIdentitySinglePk =
      engine === "sqlite" && isSinglePk && Boolean(pkCols[0].isIdentity);

    if (pkCols.length > 0 && !isSqliteIdentitySinglePk) {
      constraints.push(
        formatPrimaryKeyConstraint(
          pkCols.map((c) => c.name),
          engine,
        ),
      );
    }

    // Inline Foreign Keys:
    // - Với SQLite: giữ nguyên tất cả FKs (SQLite không hỗ trợ ALTER TABLE)
    // - Với Postgres/MySQL: chỉ giữ các FKs KHÔNG nằm trong cycleEdges
    const inlineFks = (table.foreignKeys || []).filter((fk) => {
      if (!isCycleSafe || cycleEdges.size === 0) return true;
      const edgeKey = `${table.name.toLowerCase()}->${fk.refTable.toLowerCase()}`;
      return !cycleEdges.has(edgeKey);
    });

    const sortedInlineFks = [...inlineFks].sort((a, b) => {
      const colA = a.columns.join(",");
      const colB = b.columns.join(",");
      const colCmp = colA.localeCompare(colB);
      if (colCmp !== 0) return colCmp;
      return a.refTable.localeCompare(b.refTable);
    });

    for (const fk of sortedInlineFks) {
      constraints.push(formatInlineForeignKeyConstraint(fk, table.name, engine));
    }

    // Ghép câu CREATE TABLE
    const bodyParts = [...colDefs, ...constraints];
    const quotedTable = quoteIdentifier(table.name, engine);
    let createTableSql = `CREATE TABLE ${quotedTable}`;

    if (bodyParts.length > 0) {
      createTableSql += ` (\n  ${bodyParts.join(",\n  ")}\n);`;
    } else {
      createTableSql += ` ();`;
    }

    if (engine === "mysql" && table.comment) {
      createTableSql =
        createTableSql.slice(0, -1) + ` COMMENT = '${escapeSingleQuote(table.comment)}';`;
    }

    sections.push(createTableSql);

    // Postgres comments sau CREATE TABLE
    if (engine === "postgres") {
      const commentStmts = formatPostgresComments(table);
      if (commentStmts.length > 0) {
        sections.push(commentStmts.join("\n"));
      }
    }
  }

  // 6. Khối ALTER TABLE cho các Foreign Key thuộc chu trình (chỉ Postgres và MySQL)
  if (deferredFKs.length > 0) {
    const alterBlock = [
      "-- ==============================================================",
      "-- Foreign Key Constraints (Cycle Resolution)",
      "-- ==============================================================",
      ...deferredFKs.map(({ tableName, fk }) =>
        formatAlterTableForeignKey(fk, tableName, engine),
      ),
    ].join("\n");
    sections.push(alterBlock);
  }

  return sections.join("\n\n") + "\n";
}
