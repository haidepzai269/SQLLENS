// @vitest-environment node
import { PGlite } from "@electric-sql/pglite";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { parseSchema, planData, SCHEMA_QUERY } from "./plan-data";

const DDL = `
CREATE ROLE lab_user NOSUPERUSER NOLOGIN;
GRANT ALL ON SCHEMA public TO lab_user;
SET ROLE lab_user;
CREATE TABLE customers (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE orders (id int GENERATED BY DEFAULT AS IDENTITY (START 100 INCREMENT 5) PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers(id), ticket serial);
CREATE TABLE items (id serial PRIMARY KEY, order_id int NOT NULL REFERENCES orders(id));
CREATE TABLE prices (id int PRIMARY KEY, net numeric(10,2) NOT NULL, gross numeric(10,2) GENERATED ALWAYS AS (net * 2) STORED);
CREATE TABLE "My Table" ("Id" serial PRIMARY KEY, "a""b" text NOT NULL);
CREATE TABLE "Child Of" (id serial PRIMARY KEY, p int NOT NULL REFERENCES "My Table"("Id"));
CREATE TABLE empty_t (id serial PRIMARY KEY, v int);
CREATE TABLE down (id int GENERATED BY DEFAULT AS IDENTITY (INCREMENT -1 START 1000000 MINVALUE -1000000 MAXVALUE 1000000) PRIMARY KEY, c int REFERENCES down(id));
CREATE TABLE kids (id serial PRIMARY KEY, d int NOT NULL REFERENCES down(id));`;

let db: PGlite;
const exec = async (sql: string) => (await db.query(sql, [], { rowMode: "array" })).rows as unknown[][];

beforeAll(async () => {
  db = await PGlite.create();
  await db.exec(DDL);
}, 60_000);
afterAll(() => db.close());

describe("identity / serial / generated", () => {
  it("AC1-AC6 batches run as a non-superuser; manual INSERT afterwards does not collide", async () => {
    expect((await exec("SELECT current_user, (SELECT rolsuper FROM pg_roles WHERE rolname = current_user)"))[0]).toEqual(["lab_user", false]);
    const r = await db.query(SCHEMA_QUERY, [], { rowMode: "array" });
    const tables = parseSchema({ columns: r.fields.map((f) => f.name), rows: r.rows as unknown[][] });
    const kind = (t: string, c: string) => tables.find((x) => x.name === t)!.columns.find((x) => x.name === c)!.generated;
    expect([kind("customers", "id"), kind("orders", "id"), kind("orders", "ticket"), kind("prices", "gross"), kind("prices", "id")]).toEqual([
      "identity_always", "identity_default", "serial", "stored", undefined,
    ]);

    const plan = planData(tables, { customers: 20, orders: 50, items: 30, prices: 10, "My Table": 12, "Child Of": 5, empty_t: 0 });
    for (const b of plan.batches) await db.exec(b);

    expect((await exec("SELECT count(*) FROM orders WHERE customer_id IN (SELECT id FROM customers)"))[0][0]).toBe(50);
    // AC3
    expect((await exec("SELECT count(*) FROM prices WHERE gross = net * 2"))[0][0]).toBe(10);
    // AC2, AC4: no key column written -> next value must not collide
    await db.exec("INSERT INTO customers (name) VALUES ('x')");
    await db.exec("INSERT INTO orders (customer_id) VALUES (1)");
    await db.exec("INSERT INTO items (order_id) VALUES (1)");
    expect((await exec("SELECT count(DISTINCT id) = count(*) FROM orders"))[0][0]).toBe(true);
    expect((await exec("SELECT count(DISTINCT ticket) = count(*) FROM orders"))[0][0]).toBe(true);
    expect((await exec("SELECT count(*) FROM customers"))[0][0]).toBe(21);
    // AC5: mixed-case name with spaces, reset statement present and escaped
    expect(plan.batches.some((b) => b.startsWith("SELECT setval") && b.includes(`'"public"."My Table"'`))).toBe(true);
    await db.exec(`INSERT INTO "My Table" ("a""b") VALUES ('x')`);
    expect((await exec(`SELECT count(DISTINCT "Id") = count(*) FROM "My Table"`))[0][0]).toBe(true);
    // 0-row table: no setval, insert works from the sequence start
    await db.exec("INSERT INTO empty_t (v) VALUES (1)");
    expect((await exec("SELECT id FROM empty_t"))[0][0]).toBe(1);
  }, 60_000);

  it("descending sequence: next value does not collide", async () => {
    const r = await db.query(SCHEMA_QUERY, [], { rowMode: "array" });
    const tables = parseSchema({ columns: r.fields.map((f) => f.name), rows: r.rows as unknown[][] });
    for (const b of planData(tables, { down: 10, kids: 5 }).batches) await db.exec(b);
    await db.exec("INSERT INTO down (c) VALUES (NULL)");
    expect((await exec("SELECT count(DISTINCT id) = count(*) FROM down"))[0][0]).toBe(true);
  });

  it("escapes names inside the setval literal", () => {
    const col = (name: string, extra = {}) => ({ name, type: "integer", nullable: false, isPrimaryKey: false, isUnique: false, ...extra });
    const t = [
      { schema: "public", name: "o'ne", columns: [col("i'd", { isPrimaryKey: true, generated: "serial" })] },
      { schema: "public", name: "ch", columns: [col("p", { references: { table: "o'ne", column: "i'd" } })] },
    ];
    const s = planData(t, { "o'ne": 2, ch: 2 }).batches.find((b) => b.startsWith("SELECT setval"))!;
    expect(s).toContain(`'"public"."o''ne"'`);
    expect(s).toContain(`'i''d'`);
  });
});
